-- ----------------------------------------------------------------------------
-- Kamera durumlari (AI Core heartbeat)
-- ----------------------------------------------------------------------------
CREATE TABLE kamera_durumlari (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_id         BIGINT       NOT NULL,
    kamera_adi       VARCHAR(100) NOT NULL,
    online_mi        BOOLEAN      NOT NULL DEFAULT FALSE,
    son_kare_zamani  TIMESTAMP,
    fps              DOUBLE PRECISION,
    guncelleme_zamani TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT uq_kamera_bolge_adi UNIQUE (bolge_id, kamera_adi),
    CONSTRAINT fk_kamera_bolge FOREIGN KEY (bolge_id)
        REFERENCES bolgeler (id)
);

CREATE INDEX idx_kamera_durumlari_bolge_id ON kamera_durumlari (bolge_id);
