-- ----------------------------------------------------------------------------
-- Durum: AKTIF | HATALI_TESPIT | COZULDU
-- ----------------------------------------------------------------------------
ALTER TABLE ihlaller DROP CONSTRAINT ck_ihlal_durum;

ALTER TABLE ihlaller
    ADD CONSTRAINT ck_ihlal_durum
    CHECK (durum IN ('AKTIF', 'HATALI_TESPIT', 'COZULDU'));

ALTER TABLE ihlaller
    ADD COLUMN cozen_kullanici_id BIGINT,
    ADD COLUMN cozme_zamani TIMESTAMP;

ALTER TABLE ihlaller
    ADD CONSTRAINT fk_ihlal_cozen_kullanici
    FOREIGN KEY (cozen_kullanici_id) REFERENCES kullanicilar (id);

-- ----------------------------------------------------------------------------
-- TABLO-6 : personeller
-- Kamerada tespit edilen / sicil ile eslesen saha personeli.
-- kullanicilar (login) tablosundan bagimsizdir.
-- ----------------------------------------------------------------------------
CREATE TABLE personeller (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sicil_no   VARCHAR(50)  NOT NULL,
    ad_soyad   VARCHAR(100) NOT NULL,
    departman  VARCHAR(100),
    bolge_id   BIGINT,
    aktif_mi   BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_personel_sicil UNIQUE (sicil_no),
    CONSTRAINT fk_personel_bolge FOREIGN KEY (bolge_id)
        REFERENCES bolgeler (id)
);

CREATE INDEX idx_personeller_bolge_id ON personeller (bolge_id);

ALTER TABLE ihlaller
    ADD COLUMN personel_id BIGINT;

ALTER TABLE ihlaller
    ADD CONSTRAINT fk_ihlal_personel
    FOREIGN KEY (personel_id) REFERENCES personeller (id);

CREATE INDEX idx_ihlaller_personel_id ON ihlaller (personel_id);

