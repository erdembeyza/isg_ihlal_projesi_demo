-- ----------------------------------------------------------------------------
-- TABLO-1 : bolgeler
-- Fabrika icindeki uretim bolgelerini (vardiya/departman) tanimlayan referans
-- tablosu. Formen yetkilendirmesi ve ihlal kayitlarinin konumlandirilmasi bu
-- tabloya bagli bolge_id uzerinden yapilir.
-- ----------------------------------------------------------------------------
CREATE TABLE bolgeler (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_adi VARCHAR(100) NOT NULL,
    aciklama  VARCHAR(255)
);

-- ----------------------------------------------------------------------------
-- TABLO-2 : ihlal_tipleri
-- Tespit edilebilecek KDD (Kisisel Koruyucu Donanim) ihlal tiplerini
-- tanimlayan referans/lookup tablosu (BARET / YELEK / GOZLUK).
-- ----------------------------------------------------------------------------
CREATE TABLE ihlal_tipleri (
    id       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tip_adi  VARCHAR(50) NOT NULL,
    aciklama VARCHAR(255)
);

-- ----------------------------------------------------------------------------
-- TABLO-3 : kullanicilar
-- Sisteme giris yapacak ISG yoneticisi ve formen rolundeki kurumsal
-- personeli tutan tablo.
-- ----------------------------------------------------------------------------
CREATE TABLE kullanicilar (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kullanici_adi VARCHAR(50)  NOT NULL,
    sifre_hash    VARCHAR(255) NOT NULL,
    ad_soyad      VARCHAR(100) NOT NULL,
    rol           VARCHAR(20)  NOT NULL,
    bolge_id      BIGINT,
    aktif_mi      BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_kullanici_adi UNIQUE (kullanici_adi),
    CONSTRAINT ck_kullanici_rol CHECK (rol IN ('ISG_YONETICI', 'FORMEN')),
    CONSTRAINT fk_kullanici_bolge FOREIGN KEY (bolge_id)
        REFERENCES bolgeler (id)
);

-- ----------------------------------------------------------------------------
-- TABLO-4 : ihlaller
-- Python AI Core servisi tarafindan tespit edilen her bir KDD ihlalinin
-- kanit fotograflari, konumu, zamani ve inceleme durumu ile kaydedildigi
-- sistemin ana islem (transactional) tablosu.
-- ----------------------------------------------------------------------------
CREATE TABLE ihlaller (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolge_id               BIGINT       NOT NULL,
    ihlal_tipi_id          SMALLINT     NOT NULL,
    tespit_zamani          TIMESTAMP    NOT NULL,
    orijinal_foto_yolu     VARCHAR(500) NOT NULL,
    blurlu_foto_yolu       VARCHAR(500) NOT NULL,
    durum                  VARCHAR(20)  NOT NULL DEFAULT 'AKTIF',
    reddeden_kullanici_id  BIGINT,
    red_zamani             TIMESTAMP,
    olusturma_zamani       TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_ihlal_durum CHECK (durum IN ('AKTIF', 'HATALI_TESPIT')),
    CONSTRAINT fk_ihlal_bolge FOREIGN KEY (bolge_id)
        REFERENCES bolgeler (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ihlal_tip FOREIGN KEY (ihlal_tipi_id)
        REFERENCES ihlal_tipleri (id),
    CONSTRAINT fk_ihlal_red_kullanici FOREIGN KEY (reddeden_kullanici_id)
        REFERENCES kullanicilar (id)
);

-- Rol bazli filtreleme (formen -> WHERE bolge_id=...) ve durum bazli
-- istatistik sorgulari sik kullanilacagindan destekleyici indeksler:
CREATE INDEX idx_ihlaller_bolge_id ON ihlaller (bolge_id);
CREATE INDEX idx_ihlaller_ihlal_tipi_id ON ihlaller (ihlal_tipi_id);
CREATE INDEX idx_ihlaller_durum ON ihlaller (durum);
CREATE INDEX idx_ihlaller_tespit_zamani ON ihlaller (tespit_zamani);

-- ----------------------------------------------------------------------------
-- TABLO-5 : islem_loglari
-- Kullanicilarin sistem uzerinde gerceklestirdigi kritik islemleri (giris,
-- ihlal reddetme vb.) izlenebilirlik ve denetim amaciyla kaydeden log tablosu.
-- ----------------------------------------------------------------------------
CREATE TABLE islem_loglari (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kullanici_id     BIGINT      NOT NULL,
    islem_tipi       VARCHAR(50) NOT NULL,
    ilgili_ihlal_id  BIGINT,
    islem_zamani     TIMESTAMP   NOT NULL,
    detay            VARCHAR(255),

    CONSTRAINT fk_log_kullanici FOREIGN KEY (kullanici_id)
        REFERENCES kullanicilar (id),
    CONSTRAINT fk_log_ihlal FOREIGN KEY (ilgili_ihlal_id)
        REFERENCES ihlaller (id)
);

CREATE INDEX idx_islem_loglari_kullanici_id ON islem_loglari (kullanici_id);
CREATE INDEX idx_islem_loglari_ilgili_ihlal_id ON islem_loglari (ilgili_ihlal_id);
