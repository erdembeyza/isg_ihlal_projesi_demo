CREATE TABLE personel_yuzleri (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_id       BIGINT       NOT NULL,
    foto_yolu         VARCHAR(500) NOT NULL,
    olusturma_zamani  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_personel_yuz_personel
        FOREIGN KEY (personel_id) REFERENCES personeller (id) ON DELETE CASCADE
);

CREATE INDEX idx_personel_yuzleri_personel_id ON personel_yuzleri (personel_id);
